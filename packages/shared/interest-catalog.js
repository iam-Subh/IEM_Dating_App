const aliases = new Map();
const options = INTEREST_CATEGORIES.flatMap(category => category.interests);
for (const option of options) aliases.set(option.id, option.id);
for (const option of options) {
  for (const alias of [option.label.toLowerCase(), option.label.toLowerCase().replace(/[^a-z0-9]/g, '_')]) {
    if (aliases.has(alias) && aliases.get(alias) !== option.id)
      throw new Error('Conflicting interest alias: ' + alias);
    aliases.set(alias, option.id);
  }
}
// Preserve unknown values exactly. Only recognized IDs, labels, and legacy aliases change.
function normalizeInterest(value) {
  return aliases.get(value.trim().toLowerCase()) ?? value;
}
function normalizeInterests(values) {
  return Array.isArray(values) ? [...new Set(values.filter(value => typeof value === 'string').map(normalizeInterest))] : [];
}
// Match historical snapshots before the owner runs the backfill.
function interestLookupValues(values) {
  const canonical = new Set(normalizeInterests(values));
  return [...new Set([...canonical, ...[...aliases].filter(([,id]) => canonical.has(id)).map(([alias]) => alias)])];
}
module.exports = { INTEREST_CATEGORIES, normalizeInterest, normalizeInterests, interestLookupValues };
