/**
 * Demo distances as bands in your unit, like real cards: read at render, so
 * switching km / mi in Settings changes them too.
 */
const DEMO_KM: Record<string, number> = { aanya: 2, rohan: 7, rupsa: 1, subh: 3 };
for (const demo of demoProfiles) {
  const km = DEMO_KM[demo.id];
  if (km === undefined) continue;
  Object.defineProperty(demo, "distanceLabel", {
    enumerable: true,
    configurable: true,
    get: () => distanceBand(km, unitOf(store.getState().auth.user as any)),
  });
}
